/** Decode the handful of entities Next.js emits in static HTML. */
export function decodeHtml(input) {
  return input
    .replace(/&#x27;|&#39;|&apos;/g, "'")
    .replace(/&quot;|&#34;/g, '"')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&#x2F;/g, '/')
    .replace(/&nbsp;/g, ' ');
}

export function normalise(input) {
  return decodeHtml(input).replace(/\s+/g, ' ');
}
